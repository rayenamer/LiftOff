# Generates the standalone launcher for an app: one bash file holding the
# resolved settings plus the runtime code, so it keeps working even if the
# env file or Liftoff itself is moved or deleted.

LAUNCHER_RUNTIME=(common url stack folder script container main)

launcher::path() {
  printf '%s' "$LIFTOFF_DATA_DIR/launchers/$APP_SLUG.sh"
}

launcher::generate() {
  local target
  target=$(launcher::path)
  mkdir -p "$(dirname "$target")"
  chmod 700 "$(dirname "$target")"

  # Written private from the start: it may hold DOCKER_PASSWORD.
  (umask 077 && launcher::render >"$target")
  chmod 700 "$target"

  log::ok "Launcher: $target"
}

launcher::render() {
  local module
  cat <<EOF
#!/usr/bin/env bash
#
# $APP_NAME — standalone launcher generated by Liftoff on $(date '+%Y-%m-%d %H:%M').
# Source: ${APP_ENV_FILE:-environment variables}
#
# Don't edit this file: change the env file and run \`liftoff install\` again.
#
set -Eeuo pipefail

# ── Settings ──────────────────────────────────────────────────────────────────
EOF
  launcher::render_settings

  for module in "${LAUNCHER_RUNTIME[@]}"; do
    printf '\n# ── %s ──────────────────────────────────────────────────────────────────\n' "$module.sh"
    cat "$LIFTOFF_HOME/lib/runtime/$module.sh"
  done

  printf '\nrun_app "$@"\n'
}

# Every APP_* / DOCKER_* setting, shell-quoted. Empty ones are written too,
# because the runtime reads them under `set -u`.
launcher::render_settings() {
  local name
  for name in $(compgen -v | grep -E "^$CONFIG_VAR_PATTERN$" | grep -vx APP_ENV_FILE | sort); do
    printf '%s=%q\n' "$name" "${!name}"
  done
}
